# 선형 회귀 계산
# -----------------------------
x = 연도별["연도"].to_numpy(dtype=float)
y = 연도별["연평균기온"].to_numpy(dtype=float)

# 전체 기간 회귀
기울기, 절편 = np.polyfit(x, y, 1)
상관계수 = np.corrcoef(x, y)[0, 1]

시작연도 = int(연도별["연도"].min())
끝연도 = int(연도별["연도"].max())
사용연도수 = len(연도별)

# 최근 20년: 마지막 관측 연도 기준으로 20년 범위
최근20시작 = 끝연도 - 19
최근20 = 연도별[
    (연도별["연도"] >= 최근20시작) &
    (연도별["연도"] <= 끝연도)
].copy()

if len(최근20) >= 2:
    최근기울기, 최근절편 = np.polyfit(
        최근20["연도"].to_numpy(dtype=float),
        최근20["연평균기온"].to_numpy(dtype=float),
        1
    )
    최근100년변화 = 최근기울기 * 100
else:
    최근기울기 = np.nan
    최근절편 = np.nan
    최근100년변화 = np.nan

# 100년당 기온 변화량
전체100년변화 = 기울기 * 100


def 예상기온(연도):
    return 기울기 * 연도 + 절편
